package eu.nitok.jitsu.gradle.tasks

import org.gradle.api.DefaultTask
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction

/**
 * Writes a placeholder C translation unit into the native bindings of a source set.
 *
 * Every Jitsu module publishes a `bindings` feature variant, because consumers re-generate the C
 * of their dependencies from the IR and therefore link a dependency's hand written C only. A module
 * without any `src/<sourceSet>/c` would otherwise leave `CreateStaticLibrary` with no source, so the
 * task is skipped as `NO-SOURCE`, the archive is never written, and every consumer fails with
 * `cannot find lib<module>.a`.
 *
 * Emitting one empty translation unit keeps that variant's artifact present and valid. The file
 * only contains a typedef, so it is a well formed, non empty translation unit that contributes no
 * symbols.
 */
@CacheableTask
abstract class CreateBindingsPlaceholder : DefaultTask() {
    @get:Input
    abstract val moduleName: Property<String>

    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    @TaskAction
    fun create() {
        val identifier = moduleName.get().replace(Regex("\\W"), "_")
        outputFile.get().asFile.apply {
            parentFile.mkdirs()
            writeText(
                """
                /* Generated by the Jitsu Gradle plugin - do not edit.
                 * Keeps the bindings archive of this module non empty so that consumers can link
                 * it even when the module declares no native bindings of its own.
                 */
                typedef int jitsu_${identifier}_bindings_placeholder;
                """.trimIndent() + "\n"
            )
        }
    }
}
